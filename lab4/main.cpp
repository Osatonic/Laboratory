#include <iostream>
#include "TObject.h"

using namespace std;


int main()
{
    // ==================================================
    // СОЗДАЁМ МЕХАНИЗМ
    // ==================================================

    TMechanism engine("Двигатель");


    // ==================================================
    // СОЗДАЁМ УЗЛЫ
    // ==================================================

    TNode crankMechanism(
        "Кривошипно-шатунный механизм"
    );

    TNode coolingSystem(
        "Система охлаждения"
    );


    // ==================================================
    // СОЗДАЁМ ДЕТАЛИ
    // ==================================================

    TDetail piston("Поршень");

    TDetail rod("Шатун");

    TDetail crankshaft("Коленчатый вал");


    TDetail radiator("Радиатор");

    TDetail fan("Вентилятор");

    TDetail oilFilter("Масляный фильтр");


    // ==================================================
    // ДОБАВЛЯЕМ ДЕТАЛИ В УЗЕЛ
    // ==================================================

    crankMechanism.Insert(&piston);

    crankMechanism.Insert(&rod);

    crankMechanism.Insert(&crankshaft);


    // ==================================================
    // ДОБАВЛЯЕМ ДЕТАЛИ В ДРУГОЙ УЗЕЛ
    // ==================================================

    coolingSystem.Insert(&radiator);

    coolingSystem.Insert(&fan);


    // ==================================================
    // ДОБАВЛЯЕМ УЗЛЫ И ДЕТАЛЬ В МЕХАНИЗМ
    // ==================================================

    engine.Insert(&crankMechanism);

    engine.Insert(&coolingSystem);

    engine.Insert(&oilFilter);


    // ==================================================
    // ПОКАЗЫВАЕМ МЕХАНИЗМ
    // ==================================================

    cout << "====================================" << endl;
    cout << "        ИЕРАРХИЯ МЕХАНИЗМА" << endl;
    cout << "====================================" << endl;

    engine.Show();

    cout << endl;

    cout << "Элементы механизма:" << endl;

    engine.ShowItems();


    // ==================================================
    // ВЫБИРАЕМ ЗАДАННЫЙ УЗЕЛ
    // ==================================================

    cout << endl;
    cout << "====================================" << endl;
    cout << "       ВАРИАНТ №11" << endl;
    cout << "====================================" << endl;

    cout << endl;

    cout << "Заданный узел:" << endl;

    crankMechanism.Show();


    // ==================================================
    // РАБОТА ИТЕРАТОРА
    // ==================================================

    cout << endl;

    cout << "Детали (узлы), входящие в заданный узел:"
         << endl;

    crankMechanism.ForEach();


    return 0;
}