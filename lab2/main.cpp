#include "List.h"

#include <iostream>

using namespace std;


int main()
{
    cout << "===== ЛАБОРАТОРНАЯ РАБОТА №2 =====" << endl;
    cout << "===== ПЕРЕГРУЗКА ОПЕРАЦИЙ =====" << endl;
    cout << "===== ВАРИАНТ №11 =====" << endl;


    // =========================================
    // 1. Создание первого списка
    // =========================================

    cout << "\n1. ВВОД ПЕРВОГО СПИСКА" << endl;

    List L1;

    L1.Input();

    cout << "L1 = ";
    L1.Print();


    // =========================================
    // 2. Создание второго списка
    // =========================================

    cout << "\n2. ВВОД ВТОРОГО СПИСКА" << endl;

    List L2;

    L2.Input();

    cout << "L2 = ";
    L2.Print();


    // =========================================
    // 3. Конструктор копирования
    // =========================================

    cout << "\n3. КОНСТРУКТОР КОПИРОВАНИЯ" << endl;

    List L3(L1);

    cout << "L3 = ";
    L3.Print();


    // =========================================
    // 4. Оператор присваивания
    // =========================================

    cout << "\n4. ОПЕРАТОР ПРИСВАИВАНИЯ" << endl;

    List L4;

    L4 = L2;

    cout << "L4 = ";
    L4.Print();


    // =========================================
    // 5. Оператор []
    // =========================================

    cout << "\n5. ОПЕРАТОР []" << endl;

    try
    {
        cout << "L1[0] = " << L1[0] << endl;

        if (L1[0] != '\0')
        {
            L1[0] = '*';
        }

        cout << "После изменения L1[0]: ";
        L1.Print();
    }
    catch (const out_of_range& error)
    {
        cout << "Ошибка: " << error.what() << endl;
    }


    // =========================================
    // 6. Оператор +
    // =========================================

    cout << "\n6. ОПЕРАТОР +" << endl;

    List L5 = L1 + L2;

    cout << "L1 = ";
    L1.Print();

    cout << "L2 = ";
    L2.Print();

    cout << "L5 = L1 + L2 = ";
    L5.Print();


    // =========================================
    // 7. Оператор !=
    // =========================================

    cout << "\n7. ОПЕРАТОР !=" << endl;

    if (L1 != L2)
    {
        cout << "L1 и L2 не равны." << endl;
    }
    else
    {
        cout << "L1 и L2 равны." << endl;
    }


    // =========================================
    // 8. Проверка изменения L3
    // =========================================

    cout << "\n8. ПРОВЕРКА НЕЗАВИСИМОСТИ КОПИИ" << endl;

    cout << "L1 = ";
    L1.Print();

    cout << "L3 = ";
    L3.Print();

    L3[0] = '#';

    cout << "\nПосле изменения L3[0]:" << endl;

    cout << "L1 = ";
    L1.Print();

    cout << "L3 = ";
    L3.Print();


    // =========================================
    // Завершение
    // =========================================

    cout << "\n===== КОНЕЦ ПРОГРАММЫ =====" << endl;

    return 0;
}