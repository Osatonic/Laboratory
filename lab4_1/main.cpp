#include <iostream>
#include "TObject.h"

using namespace std;


int main()
{
    // =================================================
    // СОЗДАЁМ МЕХАНИЗМ
    // =================================================

    TMechanism engine("Двигатель");


    // =================================================
    // СОЗДАЁМ УЗЛЫ
    // =================================================

    TNode crankMechanism(
        "Кривошипно-шатунный механизм"
    );

    TNode coolingSystem(
        "Система охлаждения"
    );


    // =================================================
    // СОЗДАЁМ ДЕТАЛИ
    // =================================================

    TDetail piston("Поршень");

    TDetail rod("Шатун");

    TDetail crankshaft(
        "Коленчатый вал"
    );

    TDetail radiator("Радиатор");

    TDetail fan("Вентилятор");


    // =================================================
    // ПОМЕЩАЕМ ДЕТАЛИ В УЗЕЛ
    // =================================================

    crankMechanism.Insert(&piston);

    crankMechanism.Insert(&rod);

    crankMechanism.Insert(&crankshaft);


    // =================================================
    // ПОМЕЩАЕМ ДЕТАЛИ В ДРУГОЙ УЗЕЛ
    // =================================================

    coolingSystem.Insert(&radiator);

    coolingSystem.Insert(&fan);


    // =================================================
    // СОЗДАЁМ ОБЪЕКТЫ ИЗ ЛАБОРАТОРНОЙ №3
    // =================================================

    TCar car(
        "BMW",
        4
    );

    TTrain train(
        "Обычный поезд",
        12
    );

    TExpress express(
        "Сапсан",
        10,
        250
    );


    // =================================================
    // ПОМЕЩАЕМ ОБЪЕКТЫ ЛР3 В МЕХАНИЗМ
    // =================================================

    engine.Insert(&car);

    engine.Insert(&train);

    engine.Insert(&express);


    // =================================================
    // ПОМЕЩАЕМ УЗЛЫ В МЕХАНИЗМ
    // =================================================

    engine.Insert(&crankMechanism);

    engine.Insert(&coolingSystem);


    // =================================================
    // ПОКАЗЫВАЕМ СТРУКТУРУ
    // =================================================

    cout << "========================================"
         << endl;

    cout << "        ЛАБОРАТОРНАЯ РАБОТА №4"
         << endl;

    cout << "        ВАРИАНТ №11"
         << endl;

    cout << "========================================"
         << endl;


    cout << endl;

    cout << "Механизм:" << endl;

    engine.Show();


    cout << endl;

    cout << "Объекты, входящие в механизм:"
         << endl;

    engine.ShowItems();


    // =================================================
    // ВЫПОЛНЯЕМ ЗАПРОС ВАРИАНТА №11
    // =================================================

    cout << endl;

    cout << "========================================"
         << endl;

    cout << "         ЗАПРОС ВАРИАНТА №11"
         << endl;

    cout << "========================================"
         << endl;


    cout << endl;

    cout << "Заданный узел:"
         << endl;

    crankMechanism.Show();


    cout << endl;

    cout << "Наименования деталей (узлов),"
         << endl;

    cout << "входящих в заданный узел:"
         << endl;


    // ИСПОЛЬЗУЕМ ИТЕРАТОР
    crankMechanism.ForEach();


    // =================================================
    // ВТОРОЙ ПРИМЕР
    // =================================================

    cout << endl;

    cout << "========================================"
         << endl;

    cout << "Другой заданный узел:"
         << endl;

    coolingSystem.Show();


    cout << endl;

    cout << "Наименования деталей (узлов):"
         << endl;

    coolingSystem.ForEach();


    return 0;
}