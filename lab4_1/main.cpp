#include <iostream>
#include "TObject.h"

using namespace std;


int main()
{
    cout << "========================================" << endl;
    cout << "       LABORATORY WORK 4_1" << endl;
    cout << "       ADDITIONAL VERSION" << endl;
    cout << "       VARIANT 11" << endl;
    cout << "========================================" << endl;


    // =================================================
    // 1. СОЗДАЁМ ПУСТОЙ МЕХАНИЗМ
    // =================================================

    TMechanism engine("Двигатель");


    // =================================================
    // 2. СОЗДАЁМ ПУСТЫЕ УЗЛЫ
    // =================================================

    TNode crankMechanism("Кривошипно-шатунный механизм");
    TNode coolingSystem("Система охлаждения");


    // =================================================
    // 3. СОЗДАЁМ ДЕТАЛИ
    // =================================================

    TDetail piston("Поршень");
    TDetail rod("Шатун");
    TDetail crankshaft("Коленчатый вал");

    TDetail radiator("Радиатор");
    TDetail fan("Вентилятор");


    // =================================================
    // 4. ВКЛЮЧАЕМ ДЕТАЛИ В УЗЛЫ
    // =================================================

    crankMechanism.Insert(&piston);
    crankMechanism.Insert(&rod);
    crankMechanism.Insert(&crankshaft);

    coolingSystem.Insert(&radiator);
    coolingSystem.Insert(&fan);


    // =================================================
    // 5. ИСПОЛЬЗУЕМ ИЕРАРХИЮ ИЗ ЛАБОРАТОРНОЙ №3
    //
    // НЕ создаём TCar/TTrain/TExpress.
    // Используем настоящие Car/Train/Express из lab3.
    // =================================================

    Car car("BMW", 200, 4, false);
    Train train("RZD", 120, 10, false);
    Express express("Sapsan", 250, 10, true, false);


    // =================================================
    // 6. ВКЛЮЧАЕМ ОБЪЕКТЫ ЛР3 В ГРУППУ
    // =================================================

    engine.Insert(&car);
    engine.Insert(&train);
    engine.Insert(&express);


    // =================================================
    // 7. ВКЛЮЧАЕМ УЗЛЫ В МЕХАНИЗМ
    // =================================================

    engine.Insert(&crankMechanism);
    engine.Insert(&coolingSystem);


    // =================================================
    // 8. ПОКАЗ МЕХАНИЗМА
    // =================================================

    cout << endl;
    cout << "Механизм:" << endl;
    engine.Show();

    cout << endl;
    cout << "Объекты, входящие в механизм:" << endl;
    engine.ShowItems();


    // =================================================
    // 9. ЗАПРОС ВАРИАНТА №11
    //
    // Наименование всех деталей (узлов),
    // входящих в заданный узел (механизм).
    // =================================================

    cout << endl;
    cout << "========================================" << endl;
    cout << "ЗАПРОС ВАРИАНТА №11" << endl;
    cout << "========================================" << endl;

    cout << "Заданный узел:" << endl;
    cout << crankMechanism.GetName() << endl;

    cout << endl;
    cout << "Наименования деталей, входящих в узел:" << endl;

    crankMechanism.ForEach(PrintName);


    // =================================================
    // 10. ВТОРОЙ УЗЕЛ
    // =================================================

    cout << endl;
    cout << "Второй узел:" << endl;
    cout << coolingSystem.GetName() << endl;

    cout << "Наименования деталей:" << endl;

    coolingSystem.ForEach(PrintName);


    // =================================================
    // 11. ПРОВЕРКА ForEach ДЛЯ БОЛЬШОЙ ГРУППЫ
    // =================================================

    cout << endl;
    cout << "Наименования объектов механизма:" << endl;

    engine.ForEach(PrintName);


    cout << endl;
    cout << "Программа завершена." << endl;

    return 0;
}