#include <iostream>
#include "TObject.h"

using namespace std;


int main()
{
    // =================================================
    // 1. СОЗДАЁМ МЕХАНИЗМ
    // =================================================

    TMechanism engine("Двигатель");


    // =================================================
    // 2. СОЗДАЁМ УЗЛЫ
    // =================================================

    TNode crankMechanism(
        "Кривошипно-шатунный механизм"
    );

    TNode coolingSystem(
        "Система охлаждения"
    );


    // =================================================
    // 3. СОЗДАЁМ ДЕТАЛИ
    // =================================================

    TDetail piston("Поршень");

    TDetail rod("Шатун");

    TDetail crankshaft(
        "Коленчатый вал"
    );

    TDetail radiator(
        "Радиатор"
    );

    TDetail fan(
        "Вентилятор"
    );


    // =================================================
    // 4. ДОБАВЛЯЕМ ДЕТАЛИ В ПЕРВЫЙ УЗЕЛ
    // =================================================

    crankMechanism.Insert(&piston);

    crankMechanism.Insert(&rod);

    crankMechanism.Insert(&crankshaft);


    // =================================================
    // 5. ДОБАВЛЯЕМ ДЕТАЛИ ВТОРОЙ УЗЕЛ
    // =================================================

    coolingSystem.Insert(&radiator);

    coolingSystem.Insert(&fan);


    // =================================================
    // 6. СОЗДАЁМ ТРАНСПОРТНЫЕ ОБЪЕКТЫ
    //
    // Это иерархия из дополнительной версии ЛР4:
    //
    // TTransport
    //      |
    //   +--+------+
    //   |         |
    // TCar     TTrain
    //             |
    //         TExpress
    // =================================================

    TCar car(
        "BMW",
        4
    );

    TTrain train(
        "Обычный поезд",
        12
    );

    TExpress express(
        "Сапсан",
        10,
        250
    );


    // =================================================
    // 7. ДОБАВЛЯЕМ ТРАНСПОРТ В МЕХАНИЗМ
    // =================================================

    engine.Insert(&car);

    engine.Insert(&train);

    engine.Insert(&express);


    // =================================================
    // 8. ДОБАВЛЯЕМ УЗЛЫ В МЕХАНИЗМ
    // =================================================

    engine.Insert(&crankMechanism);

    engine.Insert(&coolingSystem);


    // =================================================
    // 9. ЗАГОЛОВОК ПРОГРАММЫ
    // =================================================

    cout << "========================================"
         << endl;

    cout << "       LABORATORY WORK 4"
         << endl;

    cout << "       ADDITIONAL VERSION"
         << endl;

    cout << "       VARIANT 11"
         << endl;

    cout << "========================================"
         << endl;


    // =================================================
    // 10. ПОКАЗЫВАЕМ МЕХАНИЗМ
    // =================================================

    cout << endl;

    cout << "Механизм:"
         << endl;

    engine.Show();


    // =================================================
    // 11. ПОКАЗЫВАЕМ ОБЪЕКТЫ МЕХАНИЗМА
    // =================================================

    cout << endl;

    cout << "Объекты, входящие в механизм:"
         << endl;

    engine.ShowItems();


    // =================================================
    // 12. ПОКАЗЫВАЕМ ПЕРВЫЙ УЗЕЛ
    // =================================================

    cout << endl;

    cout << "========================================"
         << endl;

    cout << "Первый узел:"
         << endl;

    crankMechanism.Show();


    cout << endl;

    cout << "Детали узла:"
         << endl;

    crankMechanism.ShowItems();


    // =================================================
    // 13. ЗАПРОС ВАРИАНТА №11
    //
    // Наименование всех деталей (узлов),
    // входящих в заданный узел
    // =================================================

    cout << endl;

    cout << "========================================"
         << endl;

    cout << "       QUERY FOR VARIANT 11"
         << endl;

    cout << "========================================"
         << endl;

    cout << endl;

    cout << "Заданный узел:"
         << endl;

    cout << crankMechanism.GetName()
         << endl;


    cout << endl;

    cout << "Наименования деталей:"
         << endl;


    // =================================================
    // 14. ИТЕРАТОР
    // =================================================
    //
    // Передаём функцию PrintName
    // в метод ForEach.
    //
    // ForEach пройдёт по всем объектам
    // и вызовет PrintName для каждого.
    // =================================================

    crankMechanism.ForEach(PrintName);


    // =================================================
    // 15. ВТОРОЙ УЗЕЛ
    // =================================================

    cout << endl;

    cout << "========================================"
         << endl;

    cout << "Второй узел:"
         << endl;

    cout << coolingSystem.GetName()
         << endl;


    cout << endl;

    cout << "Наименования деталей:"
         << endl;

    coolingSystem.ForEach(PrintName);


    // =================================================
    // 16. ИТЕРАТОР ДЛЯ МЕХАНИЗМА
    // =================================================

    cout << endl;

    cout << "========================================"
         << endl;

    cout << "Наименования объектов механизма:"
         << endl;

    engine.ForEach(PrintName);


    cout << endl;

    cout << "========================================"
         << endl;

    cout << "Программа завершена."
         << endl;

    cout << "========================================"
         << endl;


    return 0;
}